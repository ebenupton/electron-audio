#!/usr/bin/env python3
"""LPRT: the whole Lost Patrol MOD decoded on the Electron in real time.

The player (generated by lprtbuild.py) runs frames of T ULA ticks (T * 16 us).
Each frame it steps four channels' 16.8 sample pointers, fetches a 7-bit
sample for each from main RAM, scales it through a volume table and sums
them, soft-clips the sum to NX levels through a table, and feeds that to a
table-driven modulator: a finite-state machine (NS states) that picks one of
the T-tick bit patterns.  The pattern's run lengths go to &FE06, a write in
each tick but those of Cfg.skip, from tables indexed by the pattern's code.

A frame is one of: a normal frame; a service frame (a record of the song is
read and obeyed); the frame that starts a default wait; a hold (the frame
counter's low byte ran out: every 255 normal frames, and at a wait's end).
The pointers move only in normal frames.

This module is the design and the bit-exact model:
  song()      the MOD as samples, a note table and an event stream
  Player      the model: runs the stream, returns the sum of every frame
  fsm()       the modulator's tables; modulate() runs it
  ideal()     the same performance mixed ideally at 62.5 kHz (the reference)

  lprt.py [--secs N]      build everything and report the quality
"""
import argparse, os, sys
from fractions import Fraction
import numpy as np
from numba import njit
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, HERE)
from modfile import parse, linearise, PAULA

MOD = os.path.join(ROOT, "mods/lost patrol (theme).mod")
FS = 62500.0
SIL = 64                     # a silent sample byte
CH = 4


class Cfg:
    T = 8                    # ticks a frame
    main0, main1 = 0x0400, 0x8000
    rho = {1: 1.0, 3: 1.0, 6: 1.0}       # stored samples per original sample (tonal); drums are stored at the mix rate
    pad = 60                 # silence after each sample, in frames of latitude for its note-off
    tail = 1200              # likewise for a loop's wrap (the loop's start repeated after its end)
    gain = 12.0              # mix gain into the soft clip (with the bass gone: about the level of SDMLP 3c's limiter)
    amp = 0.47               # peak |x - 0.5|
    nx = 32                  # modulator input levels
    K = 16                   # modulator state cells (x 2 polarities x 2 "free" flags)
    f0 = 3500.0              # the noise-shaping zero pair
    volmerge = {55: 56, 39: 40, 23: 24}
    tol = 40                 # frames a row may start early or late before a WAIT corrects it
    hp = 450.0               # the samples are high-passed here (Hz, at their usual pitch): the speaker gives nothing below, and the bass took most of the range
    skip = (5,)              # ticks of the pattern with no &FE06 write (see tickvals; lprtbuild.py sets it from the frame it fits)
    leak = True              # a pointer's carry into its top byte is left set: it adds 1 to the next channel's fraction (or the sum)


# ------------------------------------------------------------------ the song
def resample(x, rho):
    fr = Fraction(rho).limit_denominator(4000)
    return signal.resample_poly(x, fr.numerator, fr.denominator, window=("kaiser", 9.0)), float(fr)


def song(cfg=Cfg, path=MOD):
    """Returns a dict: mem (main RAM image from cfg.main0: samples), smp
    (per sample: addr, end, loop, ratio, orig), notes [(sample, period, vol)],
    rows (play order), vols (the volume levels), rowticks."""
    samples, order, pats = parse(path)
    rows, speed = linearise(samples, order, pats)
    FM = FS / cfg.T
    periods = {}
    for r in rows:
        for c, s, p, v, vo in r:
            if not vo:
                periods.setdefault(s, set()).add(p)
    # how far into each sample any note gets (original samples)
    need, cur = {}, [None] * 4
    def close(c, t):
        if cur[c]:
            s, p, t0 = cur[c]
            need[s] = max(need.get(s, 0), (t - t0) * PAULA / p)
    for ri, r in enumerate(rows):
        for c, s, p, v, vo in r:
            if not vo:
                close(c, ri * speed * 0.02)
                cur[c] = (s, p, ri * speed * 0.02)
            elif v == 0:
                close(c, ri * speed * 0.02)
                cur[c] = None
    for c in range(4):
        close(c, len(rows) * speed * 0.02)
    maxstep = {}
    for s0, ps in periods.items():
        maxstep[s0] = PAULA / min(ps) / FM
    # the bass taken out of each sample (as SDMLP 3c's chain does to the mix), then all scaled up to the range
    data = {}
    for s in sorted(samples):
        d = samples[s]["data"].astype(float) / 128.0
        loop = samples[s]["loop"]
        if cfg.hp and s in periods:
            sos = signal.butter(2, cfg.hp, "high", fs=PAULA / float(np.median(sorted(periods[s]))), output="sos")
            if loop:
                ls, ll = loop
                f = signal.sosfiltfilt(sos, np.concatenate([d[:ls]] + [d[ls:ls + ll]] * 6))
                d = np.concatenate([f[:ls], f[ls + 2 * ll:ls + 3 * ll]])       # (a loop from the middle: it joins itself)
            else:
                d = signal.sosfiltfilt(sos, d)
        data[s] = d
    if cfg.hp:
        k = 0.98 / max(np.abs(d).max() for d in data.values())
        data = {s: d * k for s, d in data.items()}
    mem = bytearray()
    mem += bytes([SIL] * 64)                      # (the silent note lives at main0, and creeps: see Cfg.leak)
    smp = {}
    for s in sorted(samples):
        d = data[s]
        loop = samples[s]["loop"]
        if s in cfg.rho:
            rho = cfg.rho[s]
        else:
            assert len(periods[s]) == 1, (s, periods[s])
            rho = FM * list(periods[s])[0] / PAULA          # one stored sample a frame
        if loop:
            ls, ll = loop
            pages = max(1, round(ll * rho / 256))
            rho = pages * 256 / ll
            un = np.concatenate([d[:ls]] + [d[ls:ls + ll]] * 4)
            y, rho2 = resample(un, rho)
            assert abs(rho2 - rho) < 1e-9, (rho, rho2)
            ls2 = int(round(ls * rho))
            y = y[:ls2 + pages * 256 + int(cfg.tail * maxstep[s] * rho) + 8]
            info = {"loop": (ls2, pages * 256), "oloop": (ls, ll)}
        else:
            y, rho = resample(d, rho)
            y = y[:int(min(len(d), need[s] + 8) * rho) + 1]
            info = {"loop": None}
        q = np.clip(np.round(64 + 63.5 * y), 1, 127).astype(np.uint8)
        addr = cfg.main0 + len(mem)
        mem += q.tobytes()
        info.update(addr=addr, n=len(q), ratio=rho, orig=d)
        if loop:
            info["slack"] = len(q) - (info["loop"][0] + info["loop"][1])
        else:
            info["slack"] = int(cfg.pad * maxstep[s] * rho) + 8
            mem += bytes([SIL] * info["slack"])
        smp[s] = info
    vm = lambda v: cfg.volmerge.get(v, v)
    notes, vols = [], set()
    ev = []
    nxt_is_note = {}                # (row, channel) of a volume-only event -> the channel's next event is a note
    last = [None] * 4
    for ri, r in enumerate(rows):
        for c, s, p, v, vo in r:
            if last[c] is not None:
                nxt_is_note[last[c]] = not vo
            last[c] = (ri, c) if vo else None
    for ri, r in enumerate(rows):
        e = []
        for c, s, p, v, vo in r:
            v = vm(v)
            if vo and v == 0 and nxt_is_note.get((ri, c), True):
                e.append((c, -1, 0))                # a cut: the note is over
                continue
            vols.add(v)
            if vo:
                e.append((c, None, v))
            else:
                k = (s, p, v)
                if k not in notes:
                    notes.append(k)
                e.append((c, notes.index(k), v))
        ev.append(e)
    vols = sorted(vols | {64})
    return {"mem": bytes(mem), "smp": smp, "notes": notes, "rows": ev, "vols": vols,
            "rowticks": int(round(speed * 0.02 * FS)), "FM": FM}


def voltab(v):
    s = np.arange(256)
    return np.clip(np.round(32 + (np.minimum(s, 127) - 64.0) * (31.5 / 63.5) * v / 64.0), 0, 63).astype(np.uint8)


def step16(sg, cfg, s, p):
    return int(round(PAULA / p * sg["smp"][s]["ratio"] / sg["FM"] * 256))


# ------------------------------------------------------------------ the model
@njit(cache=True)
def _frames(mem, vol, ptr, step, vt, n, out, o0, plog, leak):
    for i in range(n):
        cin = 0
        for c in range(4):
            lo = (ptr[c] & 0xFFFF) + step[c] + cin
            hi = ptr[c] >> 16
            cin = 0
            if lo >= 65536:
                lo -= 65536
                hi = (hi + 1) & 255
                cin = leak
            ptr[c] = (hi << 16) | lo
            plog[o0 + i, c] = ptr[c]
        s = cin
        for c in range(4):
            s += vol[vt[c], mem[ptr[c] >> 8]]
        out[o0 + i] = s


def holds(W):
    """A wait of W normal frames: (H, the normal frames before the first
    hold).  The counter's low byte runs out after that many and then every
    255; each time is a frame in which nothing moves, H + 1 of them, the last
    leading to the next record."""
    H = (W - 1) // 255 if W > 0 else 0
    return H, W - 255 * H


def waitlen(W):
    return W + holds(W)[0] + 1


def waitfor(n):
    """The longest wait that takes at most n frames (at least none)."""
    W = max(n - 1, 0)
    while W > 0 and waitlen(W) > n:
        W -= 1
    return W


class Player:
    """Runs the song: builds the event stream as it goes (the note-offs and
    loop wraps depend on the pointers) and records every frame.

    Stream records (symbolic), each one service frame, in which no pointer
    moves: ("NOTE", c, note, last), ("VOL", c, vol index, last), ("HI", c,
    pages back, last), ("NOP", last), ("WAIT", n), ("GOTO", page index).  A group
    of records ends with last = True (one more frame, then a wait of cfg.D
    normal frames) or with a WAIT (of n normal frames); a wait has holds in
    it and ends with one (see holds()).  caps: the bytes each
    stream page holds (a GOTO moves to the next)."""

    SIZE = {"WAIT": 3}

    def __init__(self, sg, cfg=Cfg, caps=None):
        self.sg, self.cfg = sg, cfg
        self.mem = np.zeros(65536, np.uint8)
        self.mem[cfg.main0:cfg.main0 + len(sg["mem"])] = np.frombuffer(sg["mem"], np.uint8)
        self.vol = np.stack([voltab(v) for v in sg["vols"]])
        self.vix = {v: i for i, v in enumerate(sg["vols"])}
        self.caps = caps or [256] * 64

    def run(self, nrows=None, start=None):
        """start (for the hybrid: lphybrid.py): begin at start["row"], frame start["frame"], with the channels
        as start["chan"] ((pointer, step, volume index, note) each); two frames in which nothing moves come first
        (the patterns the entry code gives), and the stream ends with EXIT (no frame of its own) instead of GOTO."""
        sg, cfg = self.sg, self.cfg
        T = cfg.T
        rows = sg["rows"][:nrows] if nrows else sg["rows"]
        Dtot = int(round(sg["rowticks"] / T)) - 3
        D = waitfor(Dtot)
        self.D = D
        nf = int(len(rows) * sg["rowticks"] / T) + 20000
        out = np.zeros(nf, np.int64)
        plog = np.zeros((nf, 4), np.int64)
        meta = np.zeros((nf, 4, 2), np.int64)          # (note or -1, vol index) per frame
        ptr = np.full(4, cfg.main0 << 8, np.int64)
        step = np.zeros(4, np.int64)
        vt = np.zeros(4, np.int64)
        note = [-1] * 4
        stream = []
        self.f = 0
        page, used = 0, 0
        self.pages = [[]]

        def service():
            f = self.f
            s = 0
            for c in range(4):
                s += self.vol[vt[c], self.mem[ptr[c] >> 8]]
                plog[f, c] = ptr[c]
                meta[f, c] = (note[c], vt[c])
            out[f] = s
            self.f += 1

        def normal(W):
            f = self.f
            _frames(self.mem, self.vol, ptr, step, vt, W, out, f, plog, int(cfg.leak))
            for c in range(4):
                meta[f:f + W, c] = (note[c], vt[c])
            self.f += W

        def wait(W):
            H, n1 = holds(W)
            normal(n1)
            service()
            for _ in range(H):
                normal(255)
                service()

        def room(rec):
            """A GOTO first (its own frame) if the record would not fit in this page."""
            nonlocal page, used
            n = self.SIZE.get(rec[0], 2)
            if used + n + 2 > self.caps[page] - 1:      # (never a record at offset 254: the offset's sum must not carry)
                g = ("GOTO", page + 1)
                stream.append(g)
                self.pages[page].append(g)
                self.pages.append([])
                service()
                page, used = page + 1, 0

        def put(rec):
            nonlocal used
            stream.append(rec)
            self.pages[page].append(rec)
            used += self.SIZE.get(rec[0], 2)
            service()

        def emit(rec):
            room(rec)
            apply(rec)
            put(rec)

        def limits(c):
            """(frames until the note needs attention, frames until it must have had it), or None."""
            if note[c] < 0 or step[c] == 0:
                return None
            s = sg["notes"][note[c]][0]
            sm = sg["smp"][s]
            if sm["loop"]:
                a = sm["addr"] + sm["loop"][0] + sm["loop"][1]
            else:
                a = sm["addr"] + sm["n"]
            b = a + sm["slack"]
            n0 = max(0, -((ptr[c] - (a << 8)) // step[c]))
            n1 = ((b << 8) - 1 - ptr[c]) // step[c] - 8
            return int(n0), int(n1)

        def apply(rec):
            if rec[0] == "NOTE":
                c, n = rec[1], rec[2]
                if n < 0:
                    ptr[c] = (cfg.main0 << 8) | (ptr[c] & 255)
                    step[c] = 0
                    vt[c] = 0
                    note[c] = -1
                else:
                    s, p, v = sg["notes"][n]
                    ptr[c] = (sg["smp"][s]["addr"] << 8) | (ptr[c] & 255)
                    step[c] = step16(sg, cfg, s, p)
                    vt[c] = self.vix[v]
                    note[c] = n
            elif rec[0] == "VOL":
                vt[rec[1]] = rec[2]
            elif rec[0] == "HI":
                ptr[rec[1]] -= rec[2] << 16

        r = 0
        at_row = True
        if start:
            r = start["row"]
            self.f = self.f0 = start["frame"]
            for c, (p0, s0, v0, n0) in enumerate(start["chan"]):
                ptr[c], step[c], vt[c], note[c] = p0, s0, v0, n0
            service()
            service()
        else:
            self.f0 = 0
        while True:
            # ---- this group's records
            recs = []
            newnote = set()
            final = at_row and r == len(rows)
            if at_row and r < len(rows):
                for c, n, v in rows[r]:
                    if n is None:
                        recs.append(["VOL", c, self.vix[v], False])
                    else:
                        recs.append(["NOTE", c, n, False])
                        newnote.add(c)
                recs = [q for q in recs if not (q[0] == "NOTE" and q[2] < 0 and note[q[1]] < 0)]     # (already silent)
            if final:
                recs = [["NOTE", c, -1, False] for c in range(4)]
            for c in range(4):
                if c in newnote or final:
                    continue
                l = limits(c)
                if l and l[0] == 0:
                    sm = sg["smp"][sg["notes"][note[c]][0]]
                    if sm["loop"]:
                        recs.append(["HI", c, sm["loop"][1] // 256, False])
                    else:
                        recs.append(["NOTE", c, -1, False])
            if not recs:
                recs = [["NOP", False]]
            for rec in recs[:-1]:
                emit(tuple(rec))
            room(recs[-1])
            apply(recs[-1])              # (its frame comes once its last-of-group flag is known)
            if final:
                put(tuple(recs[-1]))
                emit(("WAIT", int(1.0 * sg["FM"])))
                wait(int(1.0 * sg["FM"]))
                last = ("EXIT",) if start else ("GOTO", 0)
                stream.append(last)
                self.pages[page].append(last)
                break
            # ---- how long until the next group
            if at_row:
                r += 1
            target = int(round(r * sg["rowticks"] / T))
            lim = [limits(c) for c in range(4)]
            dead = min([l[1] for l in lim if l] + [1 << 30])
            # (the last record's frame and the terminator's are still to come)
            nrow = target - (self.f + 2)
            Wrow = waitfor(nrow)
            if dead < max(Wrow, D if abs(nrow - Dtot) <= cfg.tol else 0):
                W = max(dead, 0)
                at_row = False
                explicit = True
            else:
                at_row = True
                explicit = abs(nrow - Dtot) > cfg.tol
                W = D if not explicit else Wrow
            if explicit:
                put(tuple(recs[-1]))
                emit(("WAIT", W))
            else:
                recs[-1][-1] = True
                put(tuple(recs[-1]))
                service()                   # the default wait's own frame
            wait(W)
        self.stream = stream
        self.nf = self.f
        f = self.f
        return out[self.f0:f], plog[self.f0:f], meta[self.f0:f]


def replay(sg, cfg, pl, nframes):
    """The stream played as the Electron plays it, for nframes frames, going
    round at the end: an independent check of the scheduling in Player.run
    (and what the second time through sounds like).  Returns the sums."""
    mem, vol = pl.mem, pl.vol
    out = np.zeros(nframes + 70000, np.int64)
    plog = np.zeros((len(out), 4), np.int64)
    ptr = np.full(4, cfg.main0 << 8, np.int64)
    step = np.zeros(4, np.int64)
    vt = np.zeros(4, np.int64)
    f = 0
    i = 0
    st = pl.stream

    def service():
        nonlocal f
        out[f] = sum(int(vol[vt[c], mem[ptr[c] >> 8]]) for c in range(4))
        f += 1

    def normal(W):
        nonlocal f
        _frames(mem, vol, ptr, step, vt, W, out, f, plog, int(cfg.leak))
        f += W

    def wait(W):
        H, n1 = holds(W)
        normal(n1)
        service()
        for _ in range(H):
            normal(255)
            service()

    while f < nframes:
        rec = st[i]
        i = (i + 1) % len(st)
        k = rec[0]
        if k == "NOTE":
            c, n = rec[1], rec[2]
            if n < 0:
                ptr[c] = (cfg.main0 << 8) | (ptr[c] & 255)
                step[c] = 0
                vt[c] = 0
            else:
                s, p, v = sg["notes"][n]
                ptr[c] = (sg["smp"][s]["addr"] << 8) | (ptr[c] & 255)
                step[c] = step16(sg, cfg, s, p)
                vt[c] = pl.vix[v]
        elif k == "VOL":
            vt[rec[1]] = rec[2]
        elif k == "HI":
            ptr[rec[1]] -= rec[2] << 16
        service()
        if k == "WAIT":
            wait(rec[1])
        elif k not in ("GOTO",) and rec[-1] is True:
            service()
            wait(pl.D)
    return out[:nframes]


# ------------------------------------------------------------------ the reference
def ideal(sg, cfg, plog, meta, f0, f1):
    """The frames f0..f1 mixed ideally at 62.5 kHz, in the units of the sum
    less its centre (128): the same pointers, read as positions in the
    original samples with linear interpolation, moving through each frame."""
    T = cfg.T
    n = (f1 - f0) * T
    out = np.zeros(n)
    k = np.arange(T) / T
    for c in range(4):
        nt = meta[f0:f1, c, 0]
        for note in np.unique(nt):
            if note < 0:
                continue
            s, p, v = sg["notes"][note]
            sm = sg["smp"][s]
            d = sm["orig"]
            idx = np.flatnonzero(nt == note) + f0
            nxt = np.minimum(idx + 1, len(plog) - 1)
            adv = (plog[nxt, c] - plog[idx, c]) / 256.0 / sm["ratio"]
            cont = (meta[nxt, c, 0] == note) & (adv >= 0) & (adv < 64)
            adv = np.where(cont, adv, 0.0)
            # the fetch truncates: on average over a note it reads the sample
            # mean(frac) of a stored sample late (1/2, unless the step is whole)
            fr = (plog[idx, c] & 255) / 256.0
            seg = np.concatenate([[0], np.cumsum(~cont[:-1] | (np.diff(idx) != 1))])
            mfr = (np.bincount(seg, fr) / np.bincount(seg))[seg]
            pos = (plog[idx, c] / 256.0 - mfr - sm["addr"]) / sm["ratio"]
            pp = (pos[:, None] + adv[:, None] * k[None, :]).reshape(-1)
            if sm["loop"]:
                ls, ll = sm["oloop"]
                pp = np.where(pp >= ls + ll, ls + np.mod(pp - ls, ll), pp)
            i0 = np.floor(pp).astype(int)
            fr = pp - i0
            ok = (i0 >= 0) & (i0 < len(d) - 1)
            i0 = np.clip(i0, 0, len(d) - 2)
            val = (d[i0] * (1 - fr) + d[i0 + 1] * fr) * ok
            # the volume in force in each frame
            vv = np.array(sg["vols"])[meta[idx, c, 1]] / 64.0
            tt = ((idx - f0)[:, None] * T + np.arange(T)[None, :]).reshape(-1)
            out[tt] += val * np.repeat(vv, T) * 31.5 * (128 / 127.0)
    return out


def softclip(z):
    return np.tanh(z)


def clipcurve(u, cfg):
    """Sum less 128 -> x (0..1)."""
    return 0.5 + cfg.amp * softclip(cfg.gain * u / 126.0)


def cliptab(cfg):
    x = clipcurve(np.arange(256) - 128.0, cfg)
    # level i is the value i / nx (i = 1 .. nx - 1): the centre, silence, is a level exactly
    return np.clip(np.round(x * cfg.nx), 1, cfg.nx - 1).astype(np.uint8)


# ------------------------------------------------------------------ the modulator
@njit(cache=True)
def _step(e1, e2, xv, a1, a2, free, T, pats, npat):
    best = 1e30
    bi = 0
    b1 = 0.0
    b2 = 0.0
    top = 1 << (T - 1)
    for i in range(npat):
        p = pats[i]
        if not free and (p & top) == 0:
            continue
        c = 0.0
        u1 = e1
        u2 = e2
        for k in range(T):
            b = (p >> (T - 1 - k)) & 1
            e = (b - xv) - a1 * u1 - a2 * u2
            c += e * e
            u2 = u1
            u1 = e
        if c < best:
            best = c
            bi = i
            b1 = u1
            b2 = u2
    return bi, b1, b2


@njit(cache=True)
def _greedy(xl, a1, a2, T, pats):
    """Continuous-state modulator (relative form).  Returns the states seen
    (e1, e2, free) and how often each pattern was used."""
    nf = len(xl)
    st = np.zeros((nf, 3))
    use = np.zeros(len(pats), np.int64)
    e1 = 0.0
    e2 = 0.0
    last = 0
    free = 1
    for f in range(nf):
        xv = xl[f] if last == 0 else 1.0 - xl[f]
        st[f, 0] = e1
        st[f, 1] = e2
        st[f, 2] = free
        i, e1, e2 = _step(e1, e2, xv, a1, a2, free, T, pats, len(pats))
        use[i] += 1
        p = pats[i]
        free = 1 if ((p >> 1) & 1) != (p & 1) else 0
        if p & 1:
            last ^= 1
            e1 = -e1
            e2 = -e2
    return st, use


@njit(cache=True)
def _nearest(cent, e1, e2):
    best = 1e30
    bi = 0
    for i in range(cent.shape[0]):
        d = (cent[i, 0] - e1) ** 2 + (cent[i, 1] - e2) ** 2
        if d < best:
            best = d
            bi = i
    return bi


@njit(cache=True)
def _build(cent, nx, a1, a2, T, pats):
    """Folded tables [free][cell][x] -> pattern index, next free, next cell."""
    K = cent.shape[1]
    pat = np.zeros((2, K, nx), np.int64)
    nfr = np.zeros((2, K, nx), np.int64)
    ncl = np.zeros((2, K, nx), np.int64)
    for fr in range(2):
        for c in range(K):
            for xi in range(nx):
                xv = max(xi, 1) / nx
                i, e1, e2 = _step(cent[fr, c, 0], cent[fr, c, 1], xv, a1, a2, fr, T, pats, len(pats))
                p = pats[i]
                if p & 1:
                    e1 = -e1
                    e2 = -e2
                f2 = 1 if ((p >> 1) & 1) != (p & 1) else 0
                pat[fr, c, xi] = i
                nfr[fr, c, xi] = f2
                ncl[fr, c, xi] = _nearest(cent[f2], e1, e2)
    return pat, nfr, ncl


def tickvals(p, T, skip=()):
    """The &FE06 values of the writes of pattern p's frame, or None if the
    pattern cannot be played.  Write j is in tick j - 2 of the pattern (so
    the first two are in the frame before); the ticks in skip (-1 .. T - 3)
    have no write.  A write's value is the length less one of the next run
    to start, and every run that starts before the next write must have that
    same length."""
    b = [(p >> (T - 1 - k)) & 1 for k in range(T)]
    need = {}
    lead0 = 0
    while lead0 < T and b[lead0] == 0:
        lead0 += 1
    need[-1] = lead0                       # the last tick's run before the frame, carried on
    for r in range(T - 1):
        if b[r] != (b[r - 1] if r else 0):
            e = r
            while e < T and b[e] == b[r]:
                e += 1
            need[r] = e - r - 1
    ws = [w for w in range(-2, T - 2) if w not in skip]
    assert ws[0] == -2
    out = [0] * T
    for i, w in enumerate(ws):
        w2 = ws[i + 1] if i + 1 < len(ws) else T - 2
        v = set(need[r] for r in range(w + 1, w2 + 1) if r in need)
        if len(v) > 1:
            return None
        out[w + 2] = v.pop() if v else 0
    return out


def fsm(xi, cfg=Cfg, verbose=True):
    """Design the modulator for the input sequence xi (levels 0..nx-1).
    Returns {"pats": the 256 relative patterns (T bits, first tick the top
    bit), "PAT", "NXT": [state][x] tables (state = last * 2K + free * K +
    cell), "s0": the initial state}."""
    from scipy.cluster.vq import kmeans2
    T, K, nx = cfg.T, cfg.K, cfg.nx
    th = 2 * np.pi * cfg.f0 / FS
    a1, a2 = -2 * np.cos(th), 1.0
    xl = np.maximum(xi, 1).astype(float) / nx
    allp = np.arange(1, 1 << T).astype(np.int64)            # (never all zeros: that run would cross two frames)
    allp = allp[[tickvals(int(p), T, cfg.skip) is not None for p in allp]]
    st, use = _greedy(xl, a1, a2, T, allp)
    if len(allp) > 256:
        keep = np.sort(np.argsort(-use, kind="stable")[:256])
        pats = allp[keep]
        st, use = _greedy(xl, a1, a2, T, pats)
    else:
        pats = allp
    cent = np.zeros((2, K, 2))
    for fr in range(2):
        pts = st[st[:, 2] == fr][:, :2]
        cent[fr], _ = kmeans2(pts, K, minit="++", seed=1)
    pat, nfr, ncl = _build(cent, nx, a1, a2, T, pats)
    NS = 4 * K
    PAT = np.zeros((NS, nx), np.int64)
    NXT = np.zeros((NS, nx), np.int64)
    for last in range(2):
        for fr in range(2):
            for c in range(K):
                s = last * 2 * K + fr * K + c
                for x in range(nx):
                    xr = (nx - max(x, 1)) if last else x
                    i = pat[fr, c, xr]
                    l2 = last ^ int(pats[i] & 1)
                    PAT[s, x] = i
                    NXT[s, x] = l2 * 2 * K + nfr[fr, c, xr] * K + ncl[fr, c, xr]
    # Silence (the centre level, which the music hardly ever sits on): whatever the state, the plain 0101
    # and on to a state that stays there.  Left to the tables the undamped error goes round cycles of 5 or
    # 7 frames, heard as a 12.5 or 13.4 kHz whine whenever the music stops.
    alt = int("10" * (T // 2) + ("1" if T & 1 else ""), 2)
    ia = int(np.flatnonzero(pats == alt)[0])
    z1 = int(_nearest(cent[1 if T % 2 == 0 else 0], 0.0, 0.0))
    assert T % 2 == 0, "an odd frame's 0101 changes polarity: not handled"
    for last in range(2):
        for s in range(last * 2 * K, (last + 1) * 2 * K):
            PAT[s, nx // 2] = ia
            NXT[s, nx // 2] = last * 2 * K + K + z1
    s0 = K + int(_nearest(cent[1], 0.0, 0.0))
    # sinit: no error, and the pattern must begin with a toggle (so it can follow anything)
    return {"pats": pats, "PAT": PAT, "NXT": NXT, "s0": s0, "sinit": int(_nearest(cent[0], 0.0, 0.0)), "T": T}


@njit(cache=True)
def _run(xi, PAT, NXT, pats, s0, T, K2):
    nf = len(xi)
    bits = np.zeros(nf * T, np.uint8)
    codes = np.zeros(nf, np.int64)
    s = s0
    for f in range(nf):
        last = 1 if s >= K2 else 0
        i = PAT[s, xi[f]]
        codes[f] = i
        p = pats[i]
        for k in range(T):
            bits[f * T + k] = ((p >> (T - 1 - k)) & 1) ^ last
        s = NXT[s, xi[f]]
    return bits, codes


def modulate(m, xi, cfg=Cfg):
    return _run(xi.astype(np.int64), m["PAT"], m["NXT"], m["pats"], m["s0"], cfg.T, 2 * cfg.K)


def ticktabs(m, skip=()):
    """tab[j][code]: the &FE06 value of write j of a pattern's frame (see tickvals)."""
    T = m["T"]
    tab = np.zeros((T, 256), np.uint8)
    for i, p in enumerate(m["pats"]):
        tab[:, i] = tickvals(int(p), T, skip)
    return tab


# ------------------------------------------------------------------ evaluation
def evaluate(cfg=Cfg, secs=30.0, start=40.0, verbose=True):
    from sdmhq import wsnr2, snr
    sg = song(cfg)
    pl = Player(sg, cfg)
    sums, plog, meta = pl.run()
    xi = cliptab(cfg)[sums]
    m = fsm(xi, cfg)
    bits, codes = modulate(m, xi, cfg)
    T = cfg.T
    f0 = int(start * FS / T)
    f1 = min(len(sums), f0 + int(secs * FS / T))
    u = ideal(sg, cfg, plog, meta, f0, f1)
    x = clipcurve(u, cfg)
    y = bits[f0 * T:f1 * T].astype(float)
    xz = np.repeat(xi[f0:f1] / cfg.nx, T)
    res = {}
    # latency: the model's frame f plays as ticks f*T.. here, so none; the mix is a hold of T ticks: half a frame
    best = None
    for d in range(0, 2 * T):
        r = wsnr2(y[d:], x[:len(x) - d] if d else x)
        if best is None or r > best[0]:
            best = (r, d)
    d = best[1]
    xs = x[:len(x) - d] if d else x
    res["total"] = best[0]
    res["total_snr"] = snr(y[d:], xs, 300, 3500)
    res["mod"] = wsnr2(y, xz)
    res["mix"] = wsnr2(xz[d:], xs)
    res["xrms"] = (x - x.mean()).std()
    nbytes = sum(Player.SIZE.get(r[0], 2) for r in pl.stream)
    from collections import Counter
    res["kinds"] = Counter(r[0] + ("+" if r[-1] is True else "") for r in pl.stream)
    res["stream"] = nbytes
    res["mem"] = len(sg["mem"])
    if verbose:
        print("T %d (%.0f Hz): samples %d bytes, stream %d records (%d bytes), %d notes, %d vols; frames %d (%.1f s)" % (
            T, FS / T, len(sg["mem"]), len(pl.stream), nbytes, len(sg["notes"]), len(sg["vols"]), len(sums), len(sums) * T / FS))
        print("  records:", dict(res["kinds"]))
        print("  x rms %.3f; modulator alone %.2f dB, mixer alone %.2f dB, total wsnr2 %.2f dB (snr 300-3500 %.2f), delay %d ticks" % (
            res["xrms"], res["mod"], res["mix"], res["total"], res["total_snr"], d))
    return res, (sg, pl, sums, plog, meta, xi, m, bits, codes)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--secs", type=float, default=30.0)
    ap.add_argument("--start", type=float, default=40.0)
    a = ap.parse_args()
